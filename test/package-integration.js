'use strict'

const assert = require('assert')
const path = require('path')
const root = path.dirname(require.resolve('sonus/package.json', { paths: [process.cwd()] }))
const Sonus = require(root)
const sonus = Sonus.init({ applyFrontend: false }, {})
assert.strictEqual(sonus.detector.sampleRate(), 16000)
assert.strictEqual(sonus.detector.numHotwords(), 1)
const result = sonus.detector.runDetection(Buffer.alloc(3200))
assert.ok(result === -2 || result === 0)
sonus.detector.destroy()
sonus.csr.destroy()
sonus.destroy()
const conversation = Sonus.init({ hotwords: -1 }, {})
assert.strictEqual(conversation.detector, undefined)
conversation.csr.destroy()
conversation.destroy()
console.log('Sonus with standalone Snowboy integration passed')
